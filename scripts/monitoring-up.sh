#!/usr/bin/env bash
# Starts Prometheus, Alertmanager and Grafana (local, loopback-only ports).
# The API's METRICS_TOKEN (from .env) is written to a gitignored file that
# Prometheus reads as its bearer token.
set -euo pipefail
cd "$(dirname "$0")/.."
token="$(grep -E '^METRICS_TOKEN=' .env | cut -d= -f2-)"
[ -n "$token" ] || { echo "Set METRICS_TOKEN in .env (32+ characters) first"; exit 1; }
# Prometheus runs as an unprivileged user: the file must be readable by it.
# Local only; production mounts the token as a container secret instead.
printf '%s' "$token" > infrastructure/monitoring/prometheus/metrics-token
chmod 0644 infrastructure/monitoring/prometheus/metrics-token

# Alert e-mails (ADR-0038): with ALERT_EMAIL_TO set, alerts are e-mailed through
# the same SMTP account as the API. The config and password file are gitignored.
env_val() { grep -E "^$1=" .env | tail -1 | cut -d= -f2-; }
alert_to="$(env_val ALERT_EMAIL_TO || true)"
if [ -n "$alert_to" ]; then
  for k in SMTP_HOST SMTP_USER SMTP_PASSWORD MAIL_FROM; do
    [ -n "$(env_val "$k" || true)" ] || { echo "Set $k in .env for alert e-mails"; exit 1; }
  done
  [[ "$alert_to" =~ ^[^[:space:]@\']+@[^[:space:]@\']+$ ]] || { echo "ALERT_EMAIL_TO is not an e-mail address"; exit 1; }
  q() { printf "'%s'" "$(printf '%s' "$1" | sed "s/'/''/g")"; }
  dir=infrastructure/monitoring/alertmanager
  printf '%s' "$(env_val SMTP_PASSWORD)" > "$dir/smtp-password"
  chmod 0644 "$dir/smtp-password"
  cat > "$dir/alertmanager.email.yml" <<YAML
# Generated by scripts/monitoring-up.sh from .env. Do not commit.
global:
  smtp_smarthost: $(q "$(env_val SMTP_HOST):$(env_val SMTP_PORT || true)")
  smtp_from: $(q "$(env_val MAIL_FROM)")
  smtp_auth_username: $(q "$(env_val SMTP_USER)")
  smtp_auth_password_file: /etc/alertmanager/smtp-password
  smtp_require_tls: true
route:
  receiver: email-oncall
  group_by: ['alertname', 'market']
  group_wait: 30s
  repeat_interval: 4h
  routes:
    - matchers: ['severity="page"']
      receiver: email-oncall
      repeat_interval: 15m
receivers:
  - name: email-oncall
    email_configs:
      - to: $(q "$alert_to")
        send_resolved: true
YAML
  export ALERTMANAGER_CONFIG=alertmanager.email.yml
  echo "Alert e-mails go to $alert_to"
else
  echo "ALERT_EMAIL_TO is not set: alerts stay in the Alertmanager UI only"
fi
docker compose up -d --no-build api
docker compose --profile monitoring up -d prometheus alertmanager grafana
echo "Prometheus http://localhost:9090 · Alertmanager http://localhost:9093 · Grafana http://localhost:3001"
