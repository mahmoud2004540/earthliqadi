#!/usr/bin/env bash
# Regenerates the edge proxy's list of Cloudflare networks (ADR-0023) from
# Cloudflare's published ranges. Run it periodically and commit the result;
# the edge only trusts the country headers and client IP from these networks.
set -euo pipefail
cd "$(dirname "$0")/../infrastructure/docker/edge/cloudflare"

tmp=$(mktemp)
trap 'rm -f "$tmp"' EXIT
{
  curl -fsSL --max-time 30 https://www.cloudflare.com/ips-v4
  echo
  curl -fsSL --max-time 30 https://www.cloudflare.com/ips-v6
  echo
} | tr -d '\r' | grep -E '^[0-9a-fA-F:.]+/[0-9]{1,3}$' > "$tmp"

count=$(wc -l < "$tmp")
if [ "$count" -lt 10 ]; then
  echo "refusing: only $count ranges downloaded" >&2
  exit 1
fi

stamp="# Generated by scripts/update-cloudflare-ips.sh on $(date -u +%Y-%m-%d) from https://www.cloudflare.com/ips-v4 and /ips-v6"
{ echo "$stamp"; sed 's/.*/set_real_ip_from &;/' "$tmp"; } > real-ip.inc
{ echo "$stamp"; sed 's/.*/& 1;/' "$tmp"; } > networks.inc
echo "wrote $count Cloudflare ranges"
